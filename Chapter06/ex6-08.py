"""
文字列をすべて大文字にするには、upperメソッドを使います。

        upperメソッド=.upper()
"""

print("We hold these truths...".upper())

"""
文字列をすべて小文字にするには、lowerメソッドを使います。
        
        lowerメソッド=.lower()
"""

print("SO IT GOES.".lower())

"""
文字列の最初の文字を大文字で書くことをキャピタライズといいます。capitalizeメソッドを使えば文字列の先頭だけを大文字に、残りを小文字に変換できます。
        
        capitalizeメソッド=.capitalize
"""

print("four score and...".capitalize())
